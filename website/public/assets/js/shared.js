/** Общие безопасные операции DOM и форматирования для обеих страниц. */
/** Найти первый элемент страницы по CSS-селектору. */
const $ = /** Выполнить локальное действие интерфейса в текущем контексте. */ (
  selector,
) => document.querySelector(selector);
/** Отформатировать стоимость в рублях для русской локали. */
const fmt =
  /** Выполнить локальное действие интерфейса в текущем контексте. */ (value) =>
    value.toLocaleString("ru-RU") + " ₽";
/** Экранировать динамический текст перед включением в HTML-разметку. */
const escapeHTML =
  /** Выполнить локальное действие интерфейса в текущем контексте. */ (value) =>
    String(value).replace(
      /[&<>"']/g,
      /** Выполнить локальное действие интерфейса в текущем контексте. */ (c) =>
        ({
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          '"': "&quot;",
          "'": "&#39;",
        })[c],
    );
